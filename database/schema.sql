-- Esquema de referencia para una base nueva; no se ejecuta al iniciar la aplicación.
CREATE TABLE IF NOT EXISTS institution (
    institution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_name VARCHAR(255) NOT NULL,
    institution_name_es VARCHAR(255),
    institution_url VARCHAR(2048),
    institution_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0
);
